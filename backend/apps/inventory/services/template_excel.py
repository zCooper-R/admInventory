def build_import_template_bytes() -> bytes:
    df = pd.DataFrame(SAMPLE_ROWS, columns=COLUMNS)

    buf = io.BytesIO()
    with pd.ExcelWriter(buf, engine="openpyxl") as writer:
        df.to_excel(writer, index=False, sheet_name="Таблица данных")

    return buf.getvalue()
